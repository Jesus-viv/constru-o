
num1 = float(input("Digite o primeiro número: "))
num2 = float(input("Digite o segundo número: "))

# Calcula a multiplicação
resultado = num1 * num2

# Verifica se é igual a 20
if resultado == 20:
    print("A multiplicação é igual a 20.")
else:
    print("A multiplicação não é igual a 20. O resultado foi:", resultado)


