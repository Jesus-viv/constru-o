cor = input("Digite uma cor (vermelho, verde, azul): ").lower()

if cor == "vermelho":
    print("Você escolheu a cor vermelha, que simboliza energia e paixão.")
elif cor == "verde":
    print("Você escolheu a cor verde, que simboliza natureza e esperança.")
elif cor == "azul":
    print("Você escolheu a cor azul, que simboliza calma e tranquilidade.")
else:
    print("Cor inválida! Digite apenas vermelho, verde ou azul.")


