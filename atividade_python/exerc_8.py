estado_civil = input("Digite seu estado civil (solteiro, casado, divorciado, viúvo): ")

if estado_civil == "solteiro":
    print("Você está solteiro. Aproveite sua liberdade!")
elif estado_civil == "casado":
    print("Você está casado. Desejo muita felicidade no casamento!")
elif estado_civil == "divorciado":
    print("Você está divorciado. Novos recomeços sempre são possíveis!")
elif estado_civil == "viúvo":
    print("Você está viúvo. Desejo força e serenidade para você.")
else:
    print("Estado civil inválido! Digite apenas solteiro, casado, divorciado ou viúvo.")


